function checkLadder() {

    if (
        !ladder.revealed ||
        ladder.finished
    ) return;

    ladder.checked = true;

    ladder.outcomes[ladder.index] = true;

    renderActions();

    notify("Проверка завершена.");
}

function nextLadder() {

    if (
        !ladder.checked ||
        ladder.finished
    ) return;

    ladder.index++;

    ladder.revealed = false;
    ladder.checked = false;

    if (ladder.index >= ladderTasks.length) {

        ladder.finished = true;

    }

    renderPage();

    scrollTop();
}

function restartLadder() {

    if (!confirm("Начать игру заново?")) {
        return;
    }

    resetLadder();

    renderPage();
}

