function readPage() {

    if (!("speechSynthesis" in window)) {

        notify("Озвучивание недоступно.");

        return;
    }

    stopReading();

    const poemElement =

        $("page").querySelector(".poem");

    const text = poemElement

        ? poemElement.innerText.trim()

        : Array.from(

            $("page").querySelectorAll(

                "h1, h2, p, td"

            )

        ).filter(item =>

            !item.closest(".answer") &&

            !item.closest(".photo-card")

        ).map(item =>

            item.innerText.trim()

        ).filter(Boolean).join(". ");

    if (!text) return;

    const speech =

        new SpeechSynthesisUtterance(text);

    speech.lang = "ru-RU";

    speech.rate = 0.85;

    const voice =

        speechSynthesis.getVoices().find(

            item => item.lang.startsWith("ru")

        );

    if (voice) {

        speech.voice = voice;

    }

    speech.onerror = event => {

        if (

            !["interrupted", "canceled"]

                .includes(event.error)

        ) {

            notify("Русская озвучка недоступна.");

        }
    };

    speechSynthesis.speak(speech);
}

function stopReading() {

    if ("speechSynthesis" in window) {

        speechSynthesis.cancel();

    }
}

