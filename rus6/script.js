function updateClock() {

    const now = new Date(

        Date.now() + 5 * 60 * 60 * 1000

    );

    $("clock").textContent =
        now.toISOString().slice(11, 19);

    $("date").textContent =
        new Intl.DateTimeFormat("ru-RU", {

            timeZone: "UTC",

            day: "numeric",

            month: "long",

            year: "numeric"

        }).format(now);
}

