function revealGame() {

    const item = $("gameAnswer");

    if (!item) return;

    game.revealed = true;

    item.open = true;

    renderActions();
}

function checkGame() {

    if (!game.revealed || game.finished) return;

    game.checked = true;

    renderPage();

    notify("Ответы проверены.");
}

function nextGame() {

    if (!game.checked || game.finished) return;

    game.index++;

    game.revealed = false;

    game.checked = false;

    if (game.index >= gameTasks.length) {

        game.finished = true;

    }

    renderPage();

    scrollTop();
}

function restartGame() {

    if (!confirm("Начать игру заново?")) return;

    resetGame();

    renderPage();
}

