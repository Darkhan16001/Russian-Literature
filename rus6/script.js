function updateAttendance() {

    $("attendance").textContent =
        studentCount + " / 25";
}

function openSettings() {

    $("studentCount").value = studentCount;

    previewSettings();

    $("settingsDialog").showModal();
}

function closeSettings() {

    $("settingsDialog").close();
}

function setCount(value) {

    $("studentCount").value =
        normalizeCount(value);

    previewSettings();
}

function changeCount(amount) {

    setCount(
        Number($("studentCount").value) + amount
    );
}

function previewSettings() {

    const count = normalizeCount(
        $("studentCount").value
    );

    document.querySelectorAll(".quick-count button")
        .forEach(button => {

            button.classList.toggle(

                "active",

                Number(button.textContent) === count

            );

        });

    $("settingsPreview").innerHTML = `

        <div class="conclusion">

            <b>

                Присутствуют: ${count} из 25.

            </b>

            <p>

                Вариант 1:

                ${Math.ceil(count / 2)} учеников.

            </p>

            <p>

                Вариант 2:

                ${Math.floor(count / 2)} учеников.

            </p>

            Все работают самостоятельно.

        </div>

    `;
}

function saveSettings() {

    const count = normalizeCount(
        $("studentCount").value
    );

    if (count !== studentCount && game.started) {

        if (!confirm(
            "Изменение количества учеников сбросит игру. Продолжить?"
        )) return;

        resetGame();
    }

    studentCount = count;

    save("rus613-count", studentCount);

    updateAttendance();

    closeSettings();

    renderPage();

    notify("Настройки сохранены.");
}

