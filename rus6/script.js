function btn(
    text,
    action,
    disabled = false,
    css = ""
) {

    return `
        <button class="${css}"
                onclick="${action}"
                ${disabled ? "disabled" : ""}>

            ${text}

        </button>
    `;
}

function setActions(html = "") {

    $("actions").innerHTML = html

        ? `<div class="label">
               ДЕЙСТВИЯ НА СТРАНИЦЕ
           </div>${html}`

        : "";
}

function renderActions() {

    const page = pages[currentPage];

    if (page.type === "start") {

        setActions(
            btn(
                "▶ Начать занятие",
                "startLesson()"
            )
        );

        return;
    }

    if (page.type === "exercise") {

        setActions(

            btn(
                "Показать все ответы",
                "showAnswers(true)"
            ) +

            btn(
                "Скрыть все ответы",
                "showAnswers(false)"
            )

        );

        return;
    }

    if (page.type === "game") {

        if (!game.started) {

            setActions(

                btn(
                    "Начать игру",
                    "startGame()",
                    studentCount === 0
                ) +

                btn(
                    "Настройки учеников",
                    "openSettings()"
                )

            );

            return;
        }

        if (game.finished) {

            setActions(

                btn(
                    "Играть заново",
                    "restartGame()"
                ) +

                btn(
                    "Итоги занятия →",
                    "move(1)"
                )

            );

            return;
        }

        setActions(

            btn(
                "Показать ответ",
                "revealGame()",
                game.revealed
            ) +

            btn(
                "✓ Ответы проверены",
                "checkGame()",
                !game.revealed || game.checked,
                "good"
            ) +

            btn(
                "Следующий этап →",
                "nextGame()",
                !game.checked
            ) +

            btn(
                "Начать заново",
                "restartGame()"
            )

        );

        return;
    }

    if (page.type === "results") {

        setActions(

            btn(
                "Домашнее задание →",
                "move(1)"
            )

        );

        return;
    }

    if (page.type === "homework") {

        setActions(

            btn(
                "Распечатать домашнее задание",
                "window.print()"
            ) +

            btn(
                "Завершить урок",
                "finishLesson()"
            ) +

            btn(
                "Вернуться на главную",
                "goTo(0)"
            )

        );

        return;
    }

    setActions(

        btn(
            "🔊 Прочитать текст",
            "readPage()"
        ) +

        btn(
            "■ Остановить чтение",
            "stopReading()"
        )

    );
}

