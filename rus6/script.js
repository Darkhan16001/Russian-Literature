let currentPage = 0;

function renderNavigation() {

    let html = "";

    pages.forEach((page, index) => {

        if (index === 0) {

            html += `
                <div class="section-title theory">

                    6.1.3. ТЕОРИЯ

                    <br>

                    40 МИНУТ

                </div>
            `;
        }

        if (index === theoryPages.length) {

            html += `
                <div class="section-title">

                    6.1.3. ЦИТАТНЫЙ ОБРАЗ

                    <br>

                    ИНДИВИДУАЛЬНАЯ РАБОТА

                    <br>

                    40 МИНУТ

                </div>
            `;
        }

        html += `
            <button class="nav-btn

                    ${index === currentPage

                        ? "active"

                        : ""}"

                    onclick="goTo(${index})">

                ${index + 1}. ${page.menu}

            </button>
        `;
    });

    $("navigation").innerHTML = html;
}

function renderPage() {

    const page = pages[currentPage];

    if (!page) return;

    const theory =
        page.section === "theory";

    let html = page.html || "";

    if (page.type === "game") {

        html = renderGame();

    }

    if (page.type === "results") {

        html = renderResults();

    }

    $("page").innerHTML = `
        <div class="page-heading">

            <span>

                ${theory

                    ? "6.1.3. ТЕОРИЯ"

                    : "6.1.3. ИНДИВИДУАЛЬНАЯ РАБОТА"}

            </span>

            <span class="page-time">

                ◷ ${page.time} мин

            </span>

        </div>

        ${html}
    `;

    $("lessonBadge").textContent = theory

        ? "ТЕОРИЯ"

        : "ИНДИВИДУАЛЬНАЯ РАБОТА";

    $("lessonBadge").classList.toggle(

        "theory",

        theory

    );

    $("pageNumber").textContent =
        `${currentPage + 1} / ${pages.length}`;

    $("progress").style.width =
        ((currentPage + 1) / pages.length * 100) + "%";

    $("prev").disabled =
        currentPage === 0;

    $("next").disabled =
        currentPage === pages.length - 1;

    renderNavigation();

    renderActions();
}

function scrollTop() {

    $("bookArea").scrollTop = 0;

    $("bookArea").scrollLeft = 0;
}

function goTo(index) {

    if (

        index < 0 ||

        index >= pages.length

    ) return;

    stopReading();

    currentPage = index;

    renderPage();

    scrollTop();

    if (innerWidth <= 800) {

        document.body.classList.add(
            "menu-hidden"
        );

    }
}

function move(amount) {

    goTo(currentPage + amount);
}

function startLesson() {

    if (!running) toggleTimer();

    notify("Занятие началось.");
}

function finishLesson() {

    if (running) toggleTimer();

    stopReading();

    notify("Занятие завершено!");
}

