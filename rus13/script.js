const canvas = $("boardCanvas");
const ctx = canvas.getContext("2d");

let drawing = false;
let activePointer = null;
let penColor = "#155bb5";
let lastPoint = null;

const boardHistory = [];

function fillBoard() {

    ctx.fillStyle = "#ffffff";

    ctx.fillRect(
        0, 0,
        canvas.width,
        canvas.height
    );
}

fillBoard();

function openBoard() {

    $("boardDialog").showModal();
}

function setPen(color) {

    penColor = color;
}

function saveBoardHistory() {

    boardHistory.push(

        ctx.getImageData(
            0, 0,
            canvas.width,
            canvas.height
        )
    );

    if (boardHistory.length > 15) {

        boardHistory.shift();
    }
}

function undoBoard() {

    if (!boardHistory.length) return;

    ctx.putImageData(
        boardHistory.pop(),
        0,
        0
    );
}

function clearBoard() {

    if (!confirm("Очистить доску?")) return;

    saveBoardHistory();

    fillBoard();
}

function boardPosition(event) {

    const rect = canvas.getBoundingClientRect();

    return {

        x: (event.clientX - rect.left) *
            canvas.width / rect.width,

        y: (event.clientY - rect.top) *
            canvas.height / rect.height

    };
}

canvas.addEventListener("pointerdown", event => {

    if (drawing || event.button > 0) return;

    event.preventDefault();

    saveBoardHistory();

    drawing = true;

    activePointer = event.pointerId;

    canvas.setPointerCapture(event.pointerId);

    lastPoint = boardPosition(event);

    ctx.lineWidth = Number($("penWidth").value);

    ctx.strokeStyle = penColor;

    ctx.fillStyle = penColor;

    ctx.lineCap = "round";

    ctx.lineJoin = "round";

    ctx.beginPath();

    ctx.arc(
        lastPoint.x,
        lastPoint.y,
        ctx.lineWidth / 2,
        0,
        Math.PI * 2
    );

    ctx.fill();
});

canvas.addEventListener("pointermove", event => {

    if (!drawing || event.pointerId !== activePointer) return;

    const point = boardPosition(event);

    ctx.beginPath();

    ctx.moveTo(lastPoint.x, lastPoint.y);

    ctx.lineTo(point.x, point.y);

    ctx.stroke();

    lastPoint = point;
});

function stopDrawing(event) {

    if (event.pointerId !== activePointer) return;

    drawing = false;

    activePointer = null;

    lastPoint = null;

    if (canvas.hasPointerCapture(event.pointerId)) {

        canvas.releasePointerCapture(event.pointerId);
    }
}

canvas.addEventListener("pointerup", stopDrawing);

canvas.addEventListener("pointercancel", stopDrawing);

canvas.addEventListener("lostpointercapture", stopDrawing);

