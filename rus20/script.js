const lineTypes = {

    subject: `
        <path d="M0 6 H100" class="syntax-line"/>
    `,

    predicate: `
        <path d="M0 3 H100 M0 9 H100"
              class="syntax-line"/>
    `,

    attribute: `
        <path d="M0 5
                 Q5 -1 10 5 T20 5 T30 5
                 T40 5 T50 5 T60 5 T70 5
                 T80 5 T90 5 T100 5"
              class="syntax-line"/>
    `,

    object: `
        <path d="M0 6 H100"
              stroke-dasharray="9 5"
              class="syntax-line"/>
    `,

    adverbial: `
        <path d="M0 6 H100"
              stroke-dasharray="11 4 2 4"
              class="syntax-line"/>
    `

};

const syntaxNames = {
    subject: "Подлежащее",
    predicate: "Сказуемое",
    attribute: "Определение",
    object: "Дополнение",
    adverbial: "Обстоятельство"
};

function syntax(word, type) {

    return `
        <span class="syntax"
              title="${syntaxNames[type]}">

            ${word}

            <svg viewBox="0 0 100 12"
                 preserveAspectRatio="none"
                 aria-hidden="true">

                ${lineTypes[type]}

            </svg>

        </span>`;
}

function sentence(parts) {

    return `
        <div class="syntax-sentence">

            ${parts.map(([word, type]) =>
                type ? syntax(word, type) : word
            ).join(" ")}

        </div>`;
}

