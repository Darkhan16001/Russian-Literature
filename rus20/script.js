function selectOption(index) {

    if (!game.started ||
        game.mode !== "team" ||
        game.checked ||
        game.finished ||
        index < 0 ||
        index > 3) return;

    game.selected = index;

    renderPage();
}

function checkGame(skip = false) {

    if (!game.started ||
        game.mode !== "team" ||
        game.checked ||
        game.finished) return;

    if (!skip && game.selected === null) return;

    const task = gameTasks[game.index];

    if (skip) game.selected = null;

    if (!skip && game.selected === task.correct) {

        game.scores[currentTeam()] += task.points;
    }

    game.checked = true;

    renderPage();
}

function nextGame() {

    if (!game.checked || game.finished) return;

    game.index++;

    game.selected = null;
    game.checked = false;

    if (game.index >= gameTasks.length) {

        game.finished = true;
    }

    renderPage();

    $("bookArea").scrollTop = 0;
}

function finishIndividual() {

    if (game.mode !== "individual") return;

    game.finished = true;

    renderPage();
}

function restartGame() {

    if (!confirm("Начать игру заново?")) return;

    resetGame();

    renderPage();
}

