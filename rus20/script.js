function newGame() {

    return {
        started: false,
        finished: false,
        mode: null,
        index: 0,
        scores: [0, 0],
        selected: null,
        checked: false
    };
}

let game = newGame();

function resetGame() {
    game = newGame();
}

function recommendedMode() {

    return settings.count < 4 ||
           settings.mode === "individual"
        ? "individual"
        : "team";
}

function currentTeam() {
    return game.index % 2;
}

function startGame(mode) {

    if (settings.count === 0) {
        notify("Нет присутствующих учеников.");
        return;
    }

    if (mode === "team" && settings.count < 4) {
        notify("Для двух команд необходимо минимум 4 ученика.");
        return;
    }

    resetGame();

    game.started = true;
    game.mode = mode;

    renderPage();

    $("bookArea").scrollTop = 0;
}

