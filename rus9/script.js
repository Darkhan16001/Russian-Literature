const exam = {

    started: false,
    finished: false,
    remaining: 1200,
    deadline: 0,
    interval: null,
    variant: "both"

};

function startExam() {

    if (studentCount === 0) {
        notify("Укажите количество учеников.");
        return;
    }

    if (exam.started || exam.finished) return;

    exam.started = true;
    exam.deadline = Date.now() + exam.remaining * 1000;

    exam.interval = setInterval(tickExam, 250);

    renderPage();
}

function tickExam() {

    if (!exam.started || exam.finished) return;

    exam.remaining = Math.max(
        0,
        Math.ceil((exam.deadline - Date.now()) / 1000)
    );

    const clock = $("examClock");

    if (clock) {
        clock.textContent = formatTime(exam.remaining);
    }

    if (exam.remaining === 0) {

        finishExam(true);

    }
}

function finishExam(automatic = false) {

    if (exam.finished) return;

    if (!automatic) {

        if (!exam.started) {
            notify("Сначала начните работу.");
            return;
        }

        if (!confirm(
            "Завершить письменную работу и разрешить проверку?"
        )) return;

    }

    clearInterval(exam.interval);

    exam.started = false;
    exam.finished = true;

    renderPage();

    notify("Письменная работа завершена.");
}

function resetExam() {

    if (!confirm("Сбросить состояние тренировочного зачёта?")) return;

    clearInterval(exam.interval);

    Object.assign(exam, {

        started: false,
        finished: false,
        remaining: 1200,
        deadline: 0,
        interval: null,
        variant: "both"

    });

    renderPage();
}

function changeVariant(value) {

    if (!["both", "1", "2"].includes(value)) return;

    exam.variant = value;

    renderPage();
}

function variantNumbers() {

    return exam.variant === "both"
        ? [0, 1]
        : [Number(exam.variant) - 1];
}

