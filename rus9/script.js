function rule(title, text) {
    return `
        <div class="rule">
            <b class="blue">${title}</b>
            <p>${text}</p>
        </div>
    `;
}

function important(title, text) {
    return `
        <div class="important">
            <b class="red">${title}</b>
            <p>${text}</p>
        </div>
    `;
}

function conclusion(text) {
    return `
        <div class="conclusion">
            <b class="green">Вывод</b>
            <p>${text}</p>
        </div>
    `;
}

function table(headers, rows) {
    return `
        <div class="table-wrap">

            <table class="book-table">

                <thead>
                    <tr>
                        ${headers.map(h =>
                            `<th>${h}</th>`
                        ).join("")}
                    </tr>
                </thead>

                <tbody>

                    ${rows.map(row => `
                        <tr>
                            ${row.map(cell =>
                                `<td>${cell}</td>`
                            ).join("")}
                        </tr>
                    `).join("")}

                </tbody>

            </table>

        </div>
    `;
}

function answer(text, label = "Ответ:") {
    return `
        <details class="answer">

            <summary>Показать ответ</summary>

            <div class="answer-text">
                <b>${label}</b>
                <div>${text}</div>
            </div>

        </details>
    `;
}

function questions(items) {
    return items.map((item, i) => `

        <div class="question">

            <div class="question-title">
                ${blue((i + 1) + ".")} ${item[0]}
            </div>

            ${answer(item[1])}

        </div>

    `).join("");
}

function exercise(number, title, instruction, example = "") {
    return `
        <div class="exercise-heading">

            <span class="exercise-number">
                ${number}
            </span>

            <strong>${title}</strong>

        </div>

        <p class="writing-label">
            ✍ ВЫПОЛНИТЕ В ТЕТРАДИ
        </p>

        <div class="instruction">
            <b class="blue">Как выполнять:</b>
            <p>${instruction}</p>
        </div>

        ${example ? `
            <div class="example">
                <b class="red">Образец выполнения:</b>
                <p>${example}</p>
            </div>
        ` : ""}

    `;
}

document.addEventListener("toggle", event => {

    const item = event.target;

    if (
        !item.matches?.(".answer") ||
        !item.isConnected
    ) return;

    item.querySelector("summary").textContent =
        item.open ? "Скрыть ответ" : "Показать ответ";

}, true);

function showAnswers(value) {

    $("page").querySelectorAll(".answer").forEach(item => {
        item.open = value;
    });
}

