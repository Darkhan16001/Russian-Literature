function setActions(html = "") {
    $("actions").innerHTML = html
        ? `<div class="label">ДЕЙСТВИЯ НА СТРАНИЦЕ</div>${html}`
        : "";
}

function renderActions() {

    const page = pages[currentPage];

    if (page.type === "start") {
        setActions(
            btn(
                "▶ Начать занятие",
                "startLesson()",
                settings.count === 0,
                "good"
            )
        );

        return;
    }

    if (page.type === "exercise") {
        setActions(
            btn("Показать все ответы", "showAnswers(true)") +
            btn("Скрыть все ответы", "showAnswers(false)")
        );

        return;
    }

    if (page.type === "game") {

        if (!game.started) {
            setActions(
                btn("Настройки учеников", "openSettings()") +

                btn(
                    "Начать закрепление",
                    "startGame(recommendedMode())",
                    settings.count === 0,
                    "good"
                ) +

                btn(
                    "Командная викторина",
                    "startGame('team')",
                    settings.count < 4
                ) +

                btn(
                    "Индивидуальная работа",
                    "startGame('individual')",
                    settings.count === 0
                )
            );

            return;
        }

        if (game.finished) {
            setActions(
                btn("Начать заново", "restartGame()") +
                btn("Домашнее задание →", "move(1)")
            );

            return;
        }

        if (game.mode === "individual") {
            setActions(
                btn("Показать ответы", "showAnswers(true)") +
                btn("Скрыть ответы", "showAnswers(false)") +
                btn("Завершить проверку", "finishIndividual()", false, "good") +
                btn("Изменить режим", "restartGame()")
            );

            return;
        }

        setActions(

            ["А", "Б", "В", "Г"].map((letter, i) =>

                btn(
                    (game.selected === i ? "✓ " : "") +
                    "Вариант " + letter,

                    `selectOption(${i})`,

                    game.checked
                )

            ).join("") +

            btn(
                "✓ Проверить ответ",
                "checkGame()",
                game.selected === null || game.checked,
                "good"
            ) +

            btn(
                "Пропустить · 0 баллов",
                "checkGame(true)",
                game.checked,
                "bad"
            ) +

            btn(
                game.index === gameTasks.length - 1
                    ? "Показать итоги →"
                    : "Следующая команда →",

                "nextGame()",

                !game.checked
            )
        );

        return;
    }

    if (page.type === "homework") {

        setActions(
            btn("Распечатать домашнее задание", "window.print()") +
            btn("Завершить занятие", "finishLesson()") +
            btn("На главную", "goTo(0)")
        );

        return;
    }

    setActions(
        btn("Распечатать страницу", "window.print()")
    );
}

