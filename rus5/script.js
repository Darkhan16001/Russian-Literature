function setActions(html = "") {

    $("actions").innerHTML = html

        ? `<div class="label">
               ДЕЙСТВИЯ НА СТРАНИЦЕ
           </div>${html}`

        : "";
}

function renderActions() {

    const page = pages[currentPage];

    if (page.type === "start") {

        setActions(
            btn(
                "▶ Начать занятие",
                "startLesson()"
            )
        );

        return;
    }

    if (page.type === "exercise") {

        setActions(

            btn(
                "Показать все ответы",
                "showAnswers(true)"
            ) +

            btn(
                "Скрыть все ответы",
                "showAnswers(false)"
            )

        );

        return;
    }

    if (page.type === "lab") {

        if (!lab.started) {

            setActions(

                btn(
                    "Начать игру",
                    "startLab()",
                    studentCount === 0
                ) +

                btn(
                    "Настройки учеников",
                    "openSettings()"
                )

            );

            return;
        }

        if (lab.finished) {

            setActions(

                btn(
                    "Пройти заново",
                    "restartLab()"
                ) +

                btn(
                    "Далее →",
                    "move(1)"
                )

            );

            return;
        }

        setActions(

            btn(
                "Показать ответ",
                "revealLab()",
                lab.revealed
            ) +

            btn(
                "✓ Ответы проверены",
                "checkLab()",
                !lab.revealed || lab.checked,
                "good"
            ) +

            btn(
                "Следующий этап →",
                "nextLab()",
                !lab.checked
            ) +

            btn(
                "Начать заново",
                "restartLab()"
            )

        );

        return;
    }

    if (page.type === "homework") {

        setActions(

            btn(
                "Распечатать домашнее задание",
                "window.print()"
            ) +

            btn(
                "Завершить урок",
                "finishLesson()"
            ) +

            btn(
                "На главную",
                "goTo(0)"
            )

        );

        return;
    }

    setActions(

        btn(
            "🔊 Прочитать текст",
            "readPage()"
        ) +

        btn(
            "■ Остановить чтение",
            "stopReading()"
        )

    );
}

