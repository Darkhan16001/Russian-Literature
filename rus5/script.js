const lab = {

    started: false,
    finished: false,
    index: 0,
    revealed: false,
    checked: false

};

function resetLab() {

    Object.assign(lab, {

        started: false,
        finished: false,
        index: 0,
        revealed: false,
        checked: false

    });
}

function startLab() {

    if (studentCount === 0) {

        notify("Укажите количество учеников.");

        return;
    }

    resetLab();

    lab.started = true;

    renderPage();
    scrollTop();
}

