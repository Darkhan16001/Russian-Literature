function table(headers, rows) {

    return `
        <div class="table-wrap">

            <table class="book-table">

                <thead>
                    <tr>

                        ${headers.map(h =>
                            `<th>${h}</th>`
                        ).join("")}

                    </tr>
                </thead>

                <tbody>

                    ${rows.map(row => `

                        <tr>

                            ${row.map(cell =>
                                `<td>${cell}</td>`
                            ).join("")}

                        </tr>

                    `).join("")}

                </tbody>

            </table>

        </div>
    `;
}

