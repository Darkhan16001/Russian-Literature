function sourcePage(key) {
    return "https://commons.wikimedia.org/wiki/File:" +
        encodeURIComponent(
            photos[key].file.replaceAll(" ", "_")
        );
}

function photoSources(key) {

    const p = photos[key];

    const filename = encodeURIComponent(
        p.file.replaceAll(" ", "_")
    );

    return [
        p.local,

        "https://commons.wikimedia.org/wiki/Special:FilePath/" +
        filename + "?width=960",

        "https://commons.wikimedia.org/wiki/Special:FilePath/" +
        filename
    ];
}

function photo(key) {

    const p = photos[key];

    if (!p) return "";

    return `
        <figure class="photo-card">

            <img src="${photoSources(key)[0]}"
                 alt="${p.caption}"
                 data-key="${key}"
                 data-attempt="0"
                 loading="eager"
                 onerror="retryPhoto(this)"
                 onclick="openPhoto(this)">

            <div class="photo-error" hidden>

                <strong>${p.caption}</strong>

                <p>Изображение недоступно.</p>

                <button onclick="reloadPhoto(this)">
                    Повторить загрузку
                </button>

            </div>

            <figcaption>
                ${p.caption}
            </figcaption>

            <span class="photo-credit">

                ${p.credit}<br>

                <a href="${sourcePage(key)}"
                   target="_blank"
                   rel="noopener noreferrer">

                    Оригинал и лицензия

                </a>

            </span>

        </figure>
    `;
}

async function retryPhoto(img) {

    if (!img.isConnected) return;

    const key = img.dataset.key;
    const sources = photoSources(key);

    const attempt = Number(img.dataset.attempt) + 1;

    img.dataset.attempt = attempt;

    if (attempt < sources.length) {

        img.src = sources[attempt];

        return;
    }

    if (attempt === sources.length) {

        try {

            const params = new URLSearchParams({
                action: "query",
                titles: "File:" + photos[key].file,
                prop: "imageinfo",
                iiprop: "url",
                iiurlwidth: "960",
                format: "json",
                origin: "*"
            });

            const response = await fetch(
                "https://commons.wikimedia.org/w/api.php?" +
                params
            );

            if (!response.ok) throw new Error();

            const data = await response.json();

            const result = Object.values(
                data.query.pages
            )[0];

            const info = result.imageinfo?.[0];

            const url = info?.thumburl || info?.url;

            if (url && img.isConnected) {

                img.src = url;

                return;
            }

        } catch {}
    }

    if (!img.isConnected) return;

    img.hidden = true;

    img.closest("figure")
        .querySelector(".photo-error")
        .hidden = false;
}

function reloadPhoto(button) {

    const figure = button.closest("figure");
    const img = figure.querySelector("img");

    figure.querySelector(".photo-error").hidden = true;

    img.hidden = false;
    img.dataset.attempt = "0";

    img.src = photoSources(img.dataset.key)[0];
}

function openPhoto(img) {

    if (!img.complete || !img.naturalWidth) return;

    $("largePhoto").src = img.currentSrc || img.src;

    $("photoCaption").textContent =
        photos[img.dataset.key].caption;

    $("photoDialog").showModal();
}

function closePhoto() {
    $("photoDialog").close();
}

function withPhoto(content, key) {

    return `
        <div class="reading-layout">

            <div>${content}</div>

            <div>${photo(key)}</div>

        </div>
    `;
}

