document.addEventListener("toggle", event => {
    const item = event.target;

    if (
        !item.matches?.(".answer") ||
        !item.isConnected
    ) return;

    item.querySelector("summary").textContent =
        item.open ? "Скрыть ответ" : "Показать ответ";

    if (
        item.id === "gameAnswer" &&
        item.open &&
        !game.checked
    ) {
        game.revealed = true;
        renderActions();
    }
}, true);

