function selectOption(index) {
    if (
        game.mode !== "team" ||
        game.finished ||
        game.checked ||
        game.revealed
    ) return;

    if (index < 0 || index > 3) return;

    game.selected = index;

    renderPage();
}

function checkGame() {
    if (
        game.mode !== "team" ||
        game.selected === null ||
        game.checked ||
        game.revealed ||
        game.finished
    ) return;

    const task = gameTasks[game.index];

    game.checked = true;
    game.revealed = true;

    if (game.selected === task.correct) {
        game.scores[currentTeam()] += task.points;
    }

    renderPage();
}

function revealGame() {
    if (game.finished || game.checked) return;

    game.revealed = true;

    const item = $("gameAnswer");

    if (item) item.open = true;

    renderActions();
}

function skipGame() {
    if (
        game.mode !== "team" ||
        game.finished ||
        game.checked
    ) return;

    game.selected = null;
    game.revealed = true;
    game.checked = true;

    renderPage();
}

function nextGame() {
    if (!game.checked || game.finished) return;

    game.index++;

    game.selected = null;
    game.revealed = false;
    game.checked = false;

    if (game.index >= gameTasks.length) {
        game.finished = true;
    }

    renderPage();
    scrollTop();
}

function restartGame() {
    if (!confirm("Начать игру заново?")) return;

    resetGame();
    renderPage();
}

