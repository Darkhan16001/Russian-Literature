document.addEventListener("keydown", event => {

    if (
        $("settingsDialog").open ||
        $("photoDialog").open
    ) return;

    if (
        ["INPUT", "SELECT", "BUTTON", "SUMMARY", "TEXTAREA"]
        .includes(event.target.tagName)
    ) return;

    if (
        event.ctrlKey ||
        event.altKey ||
        event.metaKey
    ) return;

    if (event.key === "ArrowRight") {

        event.preventDefault();

        move(1);
    }

    if (event.key === "ArrowLeft") {

        event.preventDefault();

        move(-1);
    }

    if (
        event.key === "+" ||
        event.key === "="
    ) {

        event.preventDefault();

        changeZoom(10);
    }

    if (event.key === "-") {

        event.preventDefault();

        changeZoom(-10);
    }

    if (event.key === "0") resetZoom();

    if (event.key.toLowerCase() === "f") fullscreen();

    if (event.key.toLowerCase() === "m") toggleMenu();
});

