function revealGame() {

    const item = $("gameAnswer");

    if (!item) return;

    item.open = true;
    game.revealed = true;

    renderActions();
}

function markGame(correct) {

    if (
        !game.started ||
        game.finished ||
        game.mode !== "team" ||
        !game.revealed ||
        game.marked !== null
    ) return;

    const task = gameTasks[game.index];

    if (!task) return;

    game.marked = correct;

    if (correct) {

        game.scores[currentTeam()] +=
            task.points;

    }

    renderPage();
}

function nextGame() {

    if (
        game.marked === null ||
        game.finished
    ) return;

    game.index++;

    game.revealed = false;
    game.marked = null;

    if (game.index >= gameTasks.length) {
        game.finished = true;
    }

    renderPage();
    scrollTop();
}

function finishGame() {

    const completed =
        game.index +
        (game.marked !== null ? 1 : 0);

    if (completed % 2 !== 0) {

        notify(
            "Сначала завершите задания обеих команд."
        );

        return;
    }

    if (!confirm("Завершить игру?")) return;

    game.finished = true;

    renderPage();
}

function restartGame() {

    if (!confirm("Начать игру заново?")) return;

    resetGameState();

    renderPage();
}

function renderWinner() {

    const title = game.scores[0] === game.scores[1]

        ? "Ничья!"

        : "Победила команда «" +
          teamNames[
              game.scores[0] > game.scores[1]
                  ? 0 : 1
          ] + "»!";

    return `
        <div class="result">

            <div style="font-size:80px">🏆</div>

            <h1>${title}</h1>

            ${scoreboard(false)}

            <div class="conclusion">

                Спасибо за активную работу!

            </div>

        </div>
    `;
}

