function load(key, fallback) {
    try {
        return JSON.parse(
            localStorage.getItem(key)
        ) ?? fallback;
    } catch {
        return fallback;
    }
}

function save(key, value) {
    try {
        localStorage.setItem(
            key,
            JSON.stringify(value)
        );
    } catch {}
}

function normalizeCount(value) {
    return Math.max(
        1,
        Math.min(
            25,
            Math.floor(Number(value) || 1)
        )
    );
}

