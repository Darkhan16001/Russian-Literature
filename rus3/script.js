function table(headers, rows) {

    return `
        <div class="table-wrap">

            <table class="book-table">

                <thead>
                    <tr>
                        ${headers.map(h =>
                            `<th>${h}</th>`
                        ).join("")}
                    </tr>
                </thead>

                <tbody>

                    ${rows.map(row => `
                        <tr>
                            ${row.map(cell =>
                                `<td>${cell}</td>`
                            ).join("")}
                        </tr>
                    `).join("")}

                </tbody>

            </table>

        </div>
    `;
}

function answer(text, label = "Ответ:") {

    return `
        <details class="answer">

            <summary>Показать ответ</summary>

            <div class="answer-text">

                <b>${label}</b>

                <div>${text}</div>

            </div>

        </details>
    `;
}

function questions(items) {

    return items.map((item, index) => `

        <div class="question">

            <div class="question-title">

                ${blue((index + 1) + ".")}

                ${item[0]}

            </div>

            ${answer(item[1])}

        </div>

    `).join("");
}

