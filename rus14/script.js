function saveSettings() {
    const count = normalizeCount($("studentCount").value);
    const mode = $("lessonMode").value;

    const changed =
        count !== settings.count ||
        mode !== settings.mode;

    if (changed && game.started) {
        if (!confirm("Изменение настроек сбросит игру. Продолжить?")) {
            return;
        }
    }

    settings = { count, mode };

    save("rus913-settings", settings);

    if (changed) resetGame();

    if (count === 0 && running) toggleTimer();

    updateAttendance();
    closeDialog("settingsDialog");
    renderPage();

    notify("Настройки сохранены.");
}

