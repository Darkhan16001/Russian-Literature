function recommendedMode() {

    return settings.count < 4 ||
           settings.mode === "individual"

        ? "individual"

        : "team";
}

function startGame(mode) {

    if (settings.count === 0) {

        notify("Укажите количество учеников.");

        return;
    }

    if (mode === "team" && settings.count < 4) {

        notify("Для двух команд необходимо не менее четырёх учеников.");

        return;
    }

    resetGameState();

    game.started = true;

    game.mode = mode;

    renderPage();

    scrollTop();
}

function currentTeam() {

    return game.index % 2;
}

