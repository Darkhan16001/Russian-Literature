function selectOption(index) {

    if (
        game.finished ||
        game.marked ||
        game.revealed ||
        game.mode !== "team"
    ) return;

    if (index < 0 || index > 3) return;

    game.selected = index;

    renderPage();
}

function checkGame() {

    if (
        game.selected === null ||
        game.marked ||
        game.finished ||
        game.mode !== "team"
    ) return;

    const task = gameTasks[game.index];

    game.marked = true;

    game.revealed = true;

    if (game.selected === task.correct) {

        game.scores[currentTeam()] += task.points;

    }

    renderPage();
}

function revealGame() {

    if (game.finished || game.marked) return;

    game.revealed = true;

    const item = $("gameAnswer");

    if (item) item.open = true;

    renderActions();
}

function skipGame() {

    if (
        game.finished ||
        game.marked ||
        game.mode !== "team"
    ) return;

    game.marked = true;

    game.revealed = true;

    game.selected = null;

    renderPage();
}

function nextGame() {

    if (!game.marked || game.finished) return;

    game.index++;

    game.selected = null;

    game.revealed = false;

    game.marked = false;

    if (game.index >= gameTasks.length) {

        game.finished = true;

    }

    renderPage();

    scrollTop();
}

function restartGame() {

    if (!confirm("Начать игру заново?")) return;

    resetGameState();

    renderPage();
}

