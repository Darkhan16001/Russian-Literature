function resetGame() {
    Object.assign(game, {
        started: false,
        finished: false,
        mode: null,
        index: 0,
        scores: [0, 0],
        selected: null,
        checked: false
    });
}

function recommendedMode() {
    return settings.count < 4 ||
           settings.mode === "individual"
        ? "individual"
        : "team";
}

function startGame(mode) {
    if (settings.count === 0) {
        notify("Укажите количество учеников.");
        return;
    }

    if (mode === "team" && settings.count < 4) {
        notify("Для двух команд необходимо минимум четыре ученика.");
        return;
    }

    resetGame();

    game.started = true;
    game.mode = mode;

    renderPage();

    $("bookArea").scrollTop = 0;
}

function currentTeam() {
    return game.index % 2;
}

function scoreboard(active = true) {
    const counts = [
        Math.ceil(settings.count / 2),
        Math.floor(settings.count / 2)
    ];

    return `
        <div class="scoreboard">

            ${game.scores.map((score, i) => `

                <div class="team
                    ${i === 1 ? "second" : ""}
                    ${active && currentTeam() === i ? "active" : ""}">

                    <b>${teamNames[i]}</b>

                    <small>${counts[i]} участников</small>

                    <strong>${score}</strong>

                    <small>
                        ${!active
                            ? "БАЛЛЫ"
                            : currentTeam() === i
                                ? "ВАШ ХОД"
                                : "ОЖИДАЕТ"}
                    </small>

                </div>

            `).join("")}

        </div>
    `;
}

