function photograph(key) {

    const photo = photos[key];

    return `
        <figure class="photo-card">

            <img src="${photo.local}"
                 alt="${photo.caption}"
                 data-photo="${key}"
                 data-attempt="0"
                 onerror="photoError(this)"
                 onclick="openPhoto(this)">

            <figcaption>${photo.caption}</figcaption>

            <span class="photo-credit">

                <a href="${photo.source}"
                   target="_blank"
                   rel="noopener noreferrer">

                    ${photo.credit}

                </a>

            </span>

        </figure>`;
}

function photoError(img) {

    const photo = photos[img.dataset.photo];

    if (!photo) return;

    if (img.dataset.attempt === "0") {

        img.dataset.attempt = "1";
        img.src = photo.url;

        return;
    }

    img.onerror = null;

    img.src = illustrationURL(photo.fallback);

    img.alt = "Учебная иллюстрация по теме";

    const figure = img.closest("figure");

    figure.querySelector("figcaption").textContent =
        "Учебная иллюстрация";

    figure.querySelector(".photo-credit").textContent =
        "Историческое фото недоступно; показана встроенная иллюстрация.";
}

function withPhoto(content, key) {
    return `
        <div class="reading-layout">
            <div>${content}</div>
            <div>${photograph(key)}</div>
        </div>`;
}

function withImage(content, key, caption) {
    return `
        <div class="reading-layout">
            <div>${content}</div>
            <div>${illustration(key, caption)}</div>
        </div>`;
}

function openPhoto(img) {

    if (!img.naturalWidth) return;

    $("largePhoto").src = img.src;
    $("photoCaption").textContent = img.alt;

    $("photoDialog").showModal();
}

