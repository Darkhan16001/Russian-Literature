function illustrationURL(key) {

    const svg = `
        <svg xmlns="http://www.w3.org/2000/svg"
             viewBox="0 0 800 500">

            ${illustrations[key] || illustrations.books}

        </svg>`;

    return "data:image/svg+xml;charset=utf-8," +
        encodeURIComponent(svg);
}

