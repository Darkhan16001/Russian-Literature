window.calculateFinal = function () {

    let total = 0;

    document.querySelectorAll(".final-score").forEach(input => {

        let n = Number(input.value) || 0;

        n = Math.max(0, Math.min(25, Math.floor(n)));

        if (input.value !== "") {
            input.value = n;
        }

        total += n;
    });

    const result = document.getElementById("finalTotal");

    if (result) {
        result.textContent = total;
    }
};