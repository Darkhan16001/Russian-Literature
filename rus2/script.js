function readPage() {

    if (!("speechSynthesis" in window)) {

        notify("Озвучивание недоступно.");

        return;
    }

    stopReading();

    const text = Array.from(

        $("page").querySelectorAll(

            "h1, h2, p, td"

        )

    )

        .filter(element =>

            !element.closest(".answer") &&

            !element.closest(".photo-card")

        )

        .map(element =>

            element.innerText.trim()

        )

        .filter(Boolean)

        .join(". ");

    if (!text) return;

    const speech =

        new SpeechSynthesisUtterance(text);

    speech.lang = "ru-RU";

    speech.rate = 0.85;

    const voice =

        speechSynthesis.getVoices().find(

            item => item.lang.startsWith("ru")

        );

    if (voice) {

        speech.voice = voice;

    }

    speech.onerror = event => {

        if (

            !["interrupted", "canceled"]

                .includes(event.error)

        ) {

            notify(

                "Русская озвучка недоступна."

            );

        }
    };

    speechSynthesis.speak(speech);
}

function stopReading() {

    if ("speechSynthesis" in window) {

        speechSynthesis.cancel();

    }
}

