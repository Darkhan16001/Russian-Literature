function formatTime(seconds) {

    const minutes = Math.floor(seconds / 60);

    const secs = seconds % 60;

    return (

        String(minutes).padStart(2, "0") +

        ":" +

        String(secs).padStart(2, "0")

    );
}

function updateTimer() {

    $("timer").textContent =

        formatTime(remaining);

    $("timer").style.color =

        remaining <= 300

            ? "#ff9696"

            : "#ffda9c";

    if (remaining > 2400) {

        $("timerStage").textContent =

            "Семинар: " +

            formatTime(remaining - 2400);

    } else if (remaining > 0) {

        $("timerStage").textContent =

            "Теория: " +

            formatTime(remaining);

    } else {

        $("timerStage").textContent =

            "Время занятия завершено";

    }
}

function tick() {

    if (!running) return;

    remaining = Math.max(

        0,

        Math.ceil(

            (deadline - Date.now()) / 1000

        )

    );

    updateTimer();

    if (

        remaining <= 2400 &&

        remaining > 0 &&

        !stageNotified

    ) {

        stageNotified = true;

        notify(

            "40 минут семинара завершились. " +

            "Переходите к теоретической части."

        );

    }

    if (remaining === 0) {

        running = false;

        clearInterval(timerInterval);

        $("timerButton").textContent =

            "Старт";

        notify(

            "80 минут истекли. Занятие завершено."

        );

    }
}

function toggleTimer() {

    if (running) {

        tick();

        running = false;

        clearInterval(timerInterval);

        $("timerButton").textContent =

            "Старт";

        return;
    }

    if (remaining === 0) {

        remaining = 80 * 60;

        stageNotified = false;

    }

    deadline =

        Date.now() + remaining * 1000;

    running = true;

    $("timerButton").textContent =

        "Пауза";

    timerInterval = setInterval(tick, 250);

    updateTimer();
}

function resetTimer() {

    clearInterval(timerInterval);

    running = false;

    remaining = 80 * 60;

    stageNotified = false;

    $("timerButton").textContent =

        "Старт";

    updateTimer();
}

