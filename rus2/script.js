function revealGame() {

    if (

        !game.started ||
        game.finished ||
        game.selected === null ||
        game.mode !== "team" ||
        game.revealed

    ) return;

    game.revealed = true;

    renderGameControls();
}

function showGameAnswer() {

    const item =
        $("page").querySelector(".answer");

    if (item) {

        item.open = true;

        revealGame();

    }
}

function markGame(correct) {

    if (

        game.finished ||
        game.selected === null ||
        !game.revealed ||
        game.marked

    ) return;

    const category =
        categories[game.selected];

    if (correct) {

        game.scores[game.team] +=
            category.points;
    }

    game.used[game.team].push(
        game.selected
    );

    game.marked = true;

    game.turns++;

    renderPage();

    notify(

        correct

            ? "Правильно! +" + category.points + " баллов"

            : "Ответ не засчитан."

    );
}

function nextGameTurn() {

    if (!game.marked || game.finished) return;

    game.selected = null;

    game.revealed = false;

    game.marked = false;

    if (

        game.used[0].length === categories.length &&
        game.used[1].length === categories.length

    ) {

        game.finished = true;

    } else {

        game.team = 1 - game.team;

    }

    renderPage();

    scrollTop();
}

function finishGame() {

    if (game.selected !== null && !game.marked) {

        notify("Сначала оцените выбранное задание.");

        return;
    }

    // Обе команды должны иметь
    // одинаковое количество ходов.

    if (game.turns % 2 !== 0) {

        notify(

            "Сначала предоставьте второй команде ход."

        );

        return;
    }

    if (!confirm("Завершить игру?")) return;

    game.finished = true;

    renderPage();

    scrollTop();
}

function restartGame() {

    if (!confirm("Обнулить результаты игры?")) {

        return;
    }

    resetGameState();

    renderPage();

    scrollTop();
}

