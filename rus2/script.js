document.addEventListener("toggle", event => {

    const item = event.target;

    if (
        !item.matches?.(".answer") ||
        !item.isConnected
    ) return;

    item.querySelector("summary").textContent =
        item.open
            ? "Скрыть ответ"
            : "Показать ответ";

}, true);

function showAnswers(value) {

    $("page").querySelectorAll(".answer")
        .forEach(item => {
            item.open = value;
        });
}

