function startGame(mode) {

    if (settings.count === 0) {

        notify("Укажите количество учеников.");

        return;
    }

    if (mode === "team" && settings.count < 4) {

        notify("Используйте самостоятельную работу.");

        return;
    }

    resetGameState();

    game.started = true;

    game.mode = mode;

    renderPage();

    scrollTop();
}

