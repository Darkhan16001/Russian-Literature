function renderPage() {

    const page = pages[currentPage];

    if (!page) return;

    let content = page.html || "";

    if (page.type === "game") {

        content = renderGame();

    } else if (

        page.type === "seminar-results"

    ) {

        content = renderSeminarResults();

    } else if (page.type === "quiz") {

        content = renderQuiz();

    }

    const isTheory =
        page.section === "theory";

    $("lessonBadge").textContent = isTheory

        ? "1.1.3 · ТЕОРИЯ"

        : "1.1.2 · СЕМИНАР";

    $("lessonBadge").classList.toggle(

        "theory",

        isTheory

    );

    $("page").innerHTML = `

        <div class="page-heading">

            <span>

                ${isTheory

                    ? "ТЕОРЕТИЧЕСКОЕ ЗАНЯТИЕ"

                    : "СЕМИНАРСКОЕ ЗАНЯТИЕ"}

            </span>

            <span class="page-time">

                ◷ ${page.time} мин

            </span>

        </div>

        ${content}

    `;

    $("pageNumber").textContent =

        `${currentPage + 1} / ${pages.length}`;

    $("progress").style.width =

        ((currentPage + 1) / pages.length * 100) + "%";

    $("prev").disabled =

        currentPage === 0;

    $("next").disabled =

        currentPage === pages.length - 1;

    renderNavigation();

    renderControls(page);
}

function scrollTop() {

    $("bookArea").scrollTop = 0;

    $("bookArea").scrollLeft = 0;
}

function goTo(index) {

    if (

        index < 0 ||

        index >= pages.length

    ) return;

    stopReading();

    currentPage = index;

    renderPage();

    scrollTop();

    if (window.innerWidth <= 800) {

        document.body.classList.add(

            "menu-hidden"

        );

    }
}

function move(amount) {

    goTo(currentPage + amount);
}

