function updateClock() {

    const now = new Date(

        Date.now() + 5 * 60 * 60 * 1000

    );

    const hours = String(

        now.getUTCHours()

    ).padStart(2, "0");

    const minutes = String(

        now.getUTCMinutes()

    ).padStart(2, "0");

    const seconds = String(

        now.getUTCSeconds()

    ).padStart(2, "0");

    $("clock").textContent =

        `${hours}:${minutes}:${seconds}`;

    $("date").textContent =

        new Intl.DateTimeFormat("ru-RU", {

            timeZone: "UTC",

            day: "numeric",

            month: "long",

            year: "numeric"

        }).format(now);
}

