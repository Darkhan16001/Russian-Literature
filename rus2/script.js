function question(number, text, solution) {

    return `
        <div class="question">

            <div class="question-title">

                ${blue(number + ".")} ${text}

            </div>

            ${answer(solution)}

        </div>
    `;
}

function questions(items) {

    return items.map((item, index) =>

        question(
            index + 1,
            item[0],
            item[1]
        )

    ).join("");
}

