function rule(title, text) {
    return `
        <div class="rule">
            ${blue(title)}
            <p>${text}</p>
        </div>`;
}

function important(title, text) {
    return `
        <div class="important">
            ${red(title)}
            <p>${text}</p>
        </div>`;
}

function conclusion(text) {
    return `
        <div class="conclusion">
            ${green("Вывод")}
            <p>${text}</p>
        </div>`;
}

function scheme(text) {
    return `<div class="scheme">${text}</div>`;
}

function table(headers, rows) {
    return `
        <div class="table-wrap">

            <table class="book-table">

                <thead>
                    <tr>
                        ${headers.map(h =>
                            `<th>${h}</th>`
                        ).join("")}
                    </tr>
                </thead>

                <tbody>
                    ${rows.map(row => `
                        <tr>
                            ${row.map(c =>
                                `<td>${c}</td>`
                            ).join("")}
                        </tr>
                    `).join("")}
                </tbody>

            </table>

        </div>`;
}

function answer(text) {
    return `
        <details class="answer">

            <summary>Показать ответ</summary>

            <div class="answer-text">
                <b>Возможный ответ:</b>
                <div>${text}</div>
            </div>

        </details>`;
}

function questions(items) {
    return items.map((item, i) => `
        <div class="question">

            <div class="question-title">
                ${blue((i + 1) + ".")} ${item[0]}
            </div>

            ${answer(item[1])}

        </div>
    `).join("");
}

function exercise(n, title, instruction) {
    return `
        <div class="exercise-heading">

            <span class="exercise-number">${n}</span>

            <strong>${title}</strong>

        </div>

        <p class="writing-label">
            ✍ ВЫПОЛНИТЕ В ТЕТРАДИ
        </p>

        <div class="instruction">
            ${instruction}
        </div>`;
}

function notebook(title, items, part) {
    return `
        <h1>Запишите в тетрадь</h1>

        <p class="writing-label">
            ✍ КОНСПЕКТ · ЧАСТЬ ${part} ИЗ 3
        </p>

        <div class="notebook">

            <h2>${title}</h2>

            ${items.map(t => `<p>${t}</p>`).join("")}

        </div>`;
}

document.addEventListener("toggle", event => {

    const item = event.target;

    if (!item.matches?.(".answer")) return;

    item.querySelector("summary").textContent =
        item.open ? "Скрыть ответ" : "Показать ответ";

}, true);

function showAnswers(value) {

    $("page").querySelectorAll(".answer").forEach(item => {

        item.open = value;

    });
}

