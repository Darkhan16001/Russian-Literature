let remaining = 4800;
let running = false;
let deadline = 0;
let timerInterval = null;
let stageNotified = false;

function formatTime(seconds) {
    return String(Math.floor(seconds / 60)).padStart(2, "0") +
        ":" + String(seconds % 60).padStart(2, "0");
}

function updateTimer() {
    $("timer").textContent = formatTime(remaining);

    $("timer").style.color =
        remaining <= 300 ? "#ff9696" : "#ffdc9d";

    $("timerStage").textContent =
        remaining > 2400
            ? "Теория: " + formatTime(remaining - 2400)
            : remaining > 0
                ? "Практика: " + formatTime(remaining)
                : "Занятие завершено";
}

function tick() {
    if (!running) return;

    remaining = Math.max(
        0, Math.ceil((deadline - Date.now()) / 1000)
    );

    updateTimer();

    if (remaining <= 2400 && remaining > 0 && !stageNotified) {
        stageNotified = true;
        notify("Теория завершена. Переходите к практике.");
    }

    if (remaining === 0) {
        running = false;
        clearInterval(timerInterval);
        $("timerButton").textContent = "Старт";
        notify("80 минут истекли.");
    }
}

function toggleTimer() {
    if (running) {
        tick();
        running = false;
        clearInterval(timerInterval);
        $("timerButton").textContent = "Старт";
        return;
    }

    if (settings.count === 0) {
        notify("Нет присутствующих учеников.");
        return;
    }

    if (remaining === 0) {
        remaining = 4800;
        stageNotified = false;
    }

    deadline = Date.now() + remaining * 1000;
    running = true;

    $("timerButton").textContent = "Пауза";

    timerInterval = setInterval(tick, 250);
    updateTimer();
}

function resetTimer() {
    clearInterval(timerInterval);

    running = false;
    remaining = 4800;
    stageNotified = false;

    $("timerButton").textContent = "Старт";
    updateTimer();
}

