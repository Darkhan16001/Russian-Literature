const morphSigns = {

    prefix: `
        <path d="M0 17 V5 H100"/>
    `,

    root: `
        <path d="M0 18 Q50 -14 100 18"/>
    `,

    suffix: `
        <path d="M0 18 L50 3 L100 18"/>
    `

};

const morphNames = {
    prefix: "Приставка",
    root: "Корень",
    suffix: "Суффикс",
    ending: "Окончание"
};

function morphPart(text, type) {

    if (type === "ending") {

        return `
            <span class="morph ending"
                  title="${text ? "Окончание" : "Нулевое окончание"}">

                ${text || "∅"}

            </span>`;
    }

    return `
        <span class="morph ${type}"
              title="${morphNames[type]}">

            ${text}

            <svg viewBox="0 0 100 20"
                 preserveAspectRatio="none"
                 aria-hidden="true">

                ${morphSigns[type] || ""}

            </svg>

        </span>`;
}

function morphWord(parts) {

    const base = parts.filter(
        part => part[1] !== "ending"
    );

    const ending = parts.find(
        part => part[1] === "ending"
    );

    const baseText = base.map(
        part => part[0]
    ).join("");

    return `
        <div class="word-display">

            <div class="morph-word">

                <span class="word-base">

                    ${base.map(([text, type]) =>
                        morphPart(text, type)
                    ).join("")}

                </span>

                ${ending
                    ? morphPart(ending[0], ending[1])
                    : ""}

            </div>

            <div class="morph-labels">

                ${parts.map(([text, type]) => `

                    <span class="morph-chip ${type}">

                        ${text || "∅"} — ${morphNames[type]}

                    </span>

                `).join("")}

            </div>

            <p class="blue" style="font-size:.75em">

                Основа: ${baseText}

            </p>

        </div>`;
}

