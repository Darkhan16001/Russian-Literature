function illustration(key, caption) {

    const svg = `
        <svg xmlns="http://www.w3.org/2000/svg"
             viewBox="0 0 800 500">

            ${illustrations[key]}

        </svg>`;

    return `
        <figure class="photo-card">

            <img
                src="data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}"
                alt="${caption}"
                onclick="openPhoto(this)">

            <figcaption>${caption}</figcaption>

            <span class="photo-credit">
                Учебная векторная иллюстрация
            </span>

        </figure>`;
}

function withImage(content, key, caption) {

    return `
        <div class="reading-layout">

            <div>${content}</div>

            <div>${illustration(key, caption)}</div>

        </div>`;
}

function openPhoto(img) {

    if (!img.naturalWidth) return;

    $("largePhoto").src = img.src;
    $("photoCaption").textContent = img.alt;

    $("photoDialog").showModal();
}

